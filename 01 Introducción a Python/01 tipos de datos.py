print(type(5)) # int -> integer -> número entero
print(type(10.5)) # float -> número de punto flotante -> número real
print(type(32j)) # complex -> número complejo
print(type("hola")) # str -> string -> texto
print(type('hola'))
print(type(True)) # bool -> booleano -> valor lógico
print(type(False))
print(type((1,2,"Hola"))) # tuple -> conjunto ordenado e inmutable de datos
print(type([1,2,"Hola"])) # list -> conjunto ordenado y mutable de datos
print(type({"llave": "valor"})) # dict -> conjunto ordenado, nombrado y mutable de datos